-- Prerequisite: Upload the five JSON files to NIH_LABEL_STAGE first.

COPY INTO SUPPLEMENT_FORMULA_WARS.RAW.SUPPLEMENT_LABELS
FROM @SUPPLEMENT_FORMULA_WARS.RAW.NIH_LABEL_STAGE
FILE_FORMAT = (TYPE = JSON)
ON_ERROR = ABORT_STATEMENT;

-- Check the number of records.
SELECT COUNT(*) AS LABEL_COUNT
FROM SUPPLEMENT_FORMULA_WARS.RAW.SUPPLEMENT_LABELS;

-- Check the label IDs and product names.
SELECT
    RAW_RECORD:id::STRING AS LABEL_ID,
    RAW_RECORD:fullName::STRING AS PRODUCT_NAME
FROM SUPPLEMENT_FORMULA_WARS.RAW.SUPPLEMENT_LABELS
ORDER BY LABEL_ID;